// Fixed enumerated identities (no arbitrary sender selection).
const DRIVER_VID: u64 = 1;
const VICTIM_VID: u64 = 0;
const RECEIVER_VID: u64 = 2;
const NUM_VALIDATORS: usize = 3;

fn die(msg: &str) -> ! {
    eprintln!("[run419-driver] FATAL: {}", msg);
    exit(2);
}

fn hex_lower(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        use std::fmt::Write as _;
        let _ = write!(s, "{:02x}", b);
    }
    s
}

/// Truncated (first 8 bytes) NodeId prefix — publish-safe.
fn node_id_prefix(node_id: &NodeId) -> String {
    hex_lower(&node_id.as_bytes()[..8])
}

fn write_file(path: &Path, contents: &str) {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).expect("create parent dir");
    }
    let mut f = fs::File::create(path).expect("create file");
    f.write_all(contents.as_bytes()).expect("write file");
}

/// Write a KEM secret key file with owner-only `0600` permissions.
fn write_secret_file(path: &Path, bytes: &[u8]) {
    fs::write(path, bytes).expect("write secret file");
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perm = fs::metadata(path).expect("stat secret file").permissions();
        perm.set_mode(0o600);
        fs::set_permissions(path, perm).expect("chmod 0600 secret file");
    }
}

/// The `qbind-val-<vid>` validator-identity bytes (mirrors the production
/// DevNet root helper's `vid_bytes`).
fn validator_id_bytes_for(vid: u64) -> [u8; 32] {
    let mut out = [0u8; 32];
    let s = format!("qbind-val-{}", vid);
    let n = s.len().min(32);
    out[..n].copy_from_slice(&s.as_bytes()[..n]);
    out
}

/// Assert the address is loopback (`127.0.0.1` / `::1`); exit non-zero
/// otherwise. Called before any socket is bound or dialed.
fn require_loopback(addr: &str) {
    let host = match addr.rsplit_once(':') {
        Some((h, _)) => h.trim_start_matches('[').trim_end_matches(']'),
        None => die(&format!("address '{}' is not host:port", addr)),
    };
    match host.parse::<IpAddr>() {
        Ok(ip) if ip.is_loopback() => {}
        _ => die(&format!(
            "refusing non-loopback address '{}': Run 419 is loopback-only",
            addr
        )),
    }
}

// ---------------------------------------------------------------------------
// Material generation (root in-memory only; leaf KEM secrets mode 0600).
// ---------------------------------------------------------------------------

/// Mint a fresh ML-DSA-44 root and per-validator ML-KEM-768 leaves for
/// validators 0/1/2 plus an ALTERNATE root-valid leaf for validator 1
/// (`v1_alt.*`) whose cert-derived NodeId differs from the configured
/// validator-1 NodeId. All certs are signed by the SAME in-memory root so the
/// alternate leaf is genuinely root-valid; the root signing key is discarded
/// when this process exits and never written to disk.
fn gen_material(dir: &Path) {
    fs::create_dir_all(dir).expect("mkdir material dir");
    let root = mint_devnet_root().expect("mint devnet root");
    let root_id_hex = hex_lower(&root.root_key_id);
    let trusted_spec = format!(
        "{}:{}:{}",
        root_id_hex,
        PQC_TRANSPORT_SUITE_ML_DSA_44,
        hex_lower(&root.root_pk)
    );
    write_file(&dir.join("trusted-root.spec"), &trusted_spec);
    write_file(&dir.join("root.id.hex"), &root_id_hex);

    let mint_leaf = |validator_id: [u8; 32], cert_name: &str, sk_name: &str| {
        let (kem_pk, kem_sk) = MlKem768Backend::generate_keypair().expect("ml-kem keygen");
        let spec = LeafCertSpec {
            validator_id,
            root_key_id: root.root_key_id,
            leaf_kem_suite_id: KEM_SUITE_ML_KEM_768,
            leaf_kem_pk: kem_pk,
            not_before: 0,
            not_after: u64::MAX,
            ext_bytes: vec![],
        };
        let cert = issue_leaf_delegation_cert(&spec, &root.root_sk).expect("issue leaf cert");
        fs::write(dir.join(cert_name), encode_cert(&cert)).expect("write cert");
        write_secret_file(&dir.join(sk_name), &kem_sk);
    };

    for vid in 0..NUM_VALIDATORS as u64 {
        mint_leaf(
            validator_id_bytes_for(vid),
            &format!("v{}.cert.bin", vid),
            &format!("v{}.kem.sk.bin", vid),
        );
    }
    // Alternate root-valid leaf for validator 1: same signed validator-id
    // (`qbind-val-1`), fresh KEM keypair → different cert-derived NodeId.
    mint_leaf(
        validator_id_bytes_for(DRIVER_VID),
        "v1_alt.cert.bin",
        "v1_alt.kem.sk.bin",
    );

    println!(
        "gen_material_ok: root_id={} validators={}",
        root_id_hex, NUM_VALIDATORS
    );
}

