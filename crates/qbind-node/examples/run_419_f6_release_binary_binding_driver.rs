fn encode_wire<T: WireEncode>(t: &T) -> Vec<u8> {
    let mut out = Vec::new();
    t.encode(&mut out);
    out
}

fn proposal_frame(proposer: u64) -> P2pMessage {
    let proposal = BlockProposal {
        header: BlockHeader {
            version: 1,
            chain_id: 1,
            epoch: 0,
            height: 0,
            round: 0,
            parent_block_id: [0xFF; 32],
            payload_hash: [0u8; 32],
            proposer_index: proposer as u16,
            suite_id: qbind_wire::DEFAULT_CONSENSUS_SUITE_ID,
            tx_count: 0,
            timestamp: 0,
            payload_kind: qbind_wire::PAYLOAD_KIND_NORMAL,
            next_epoch: 0,
            batch_commitment: [0u8; 32],
        },
        qc: None,
        txs: vec![],
        signature: vec![],
    };
    P2pMessage::Consensus(ConsensusNetMsg::Proposal(encode_wire(&proposal)))
}

fn vote_frame(voter: u64) -> P2pMessage {
    let vote = Vote {
        version: 1,
        chain_id: 1,
        epoch: 0,
        height: 0,
        round: 0,
        step: 0,
        block_id: [0u8; 32],
        validator_index: voter as u16,
        suite_id: qbind_wire::DEFAULT_CONSENSUS_SUITE_ID,
        signature: vec![],
    };
    P2pMessage::Consensus(ConsensusNetMsg::Vote(encode_wire(&vote)))
}

fn timeout_frame(sender: u64) -> P2pMessage {
    let timeout: TimeoutMsg<[u8; 32]> = TimeoutMsg {
        view: 0,
        high_qc: None,
        validator_id: ValidatorId::new(sender),
        suite_id: qbind_wire::DEFAULT_CONSENSUS_SUITE_ID as u8,
        signature: vec![],
    };
    // Match the loop's `bincode::options().with_fixint_encoding()` decode.
    let bytes = bincode::options()
        .with_fixint_encoding()
        .serialize(&timeout)
        .expect("encode timeout");
    P2pMessage::Consensus(ConsensusNetMsg::Timeout(bytes))
}

fn newview_frame() -> P2pMessage {
    let tc: TimeoutCertificate<[u8; 32]> = TimeoutCertificate {
        view: 1,
        high_qc: None,
        signers: vec![],
        signed_timeouts: vec![],
        timeout_view: 0,
    };
    let bytes = bincode::options()
        .with_fixint_encoding()
        .serialize(&tc)
        .expect("encode timeout certificate");
    P2pMessage::Consensus(ConsensusNetMsg::NewView(bytes))
}

fn restore_request_frame(requester: u64) -> P2pMessage {
    P2pMessage::Consensus(ConsensusNetMsg::RestoreCatchupRequest(
        RestoreCatchupRequest {
            requester_validator_index: requester as u16,
            from_height: 0,
            from_block_id: [0u8; 32],
        },
    ))
}

fn restore_response_frame(responder: u64) -> P2pMessage {
    P2pMessage::Consensus(ConsensusNetMsg::RestoreCatchupResponse(
        RestoreCatchupResponse {
            responder_validator_index: responder as u16,
            request_from_height: 0,
            request_from_block_id: [0u8; 32],
            responder_committed_height: None,
            blocks: vec![],
        },
    ))
}

