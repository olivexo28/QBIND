/// Build an authenticated (static-root Required) driver node and wait until the
/// receiver's cert-derived NodeId is registered as a connected peer.
async fn build_authenticated_driver(
    material_dir: &Path,
    leaf_stem: &str,
    listen_addr: &str,
    receiver_addr: &str,
) -> (P2pNodeContext, bool, bool, NodeId) {
    let config = make_config(listen_addr, receiver_addr);
    let pqc = driver_static_root_config(material_dir, leaf_stem);
    let ctx = P2pNodeBuilder::new()
        .with_num_validators(NUM_VALIDATORS)
        .with_mutual_auth_mode(MutualAuthMode::Required)
        .with_pqc_root_config(pqc)
        .build(&config, DRIVER_VID)
        .await
        .expect("build authenticated driver node");
    let receiver_node_id = cert_derived_node_id_from_file(&material_dir.join("v2.cert.bin"));
    let (connected, saw_receiver) = wait_connected(&ctx, &receiver_node_id).await;
    (ctx, connected, saw_receiver, receiver_node_id)
}

/// Build an UNAUTHENTICATED driver node in the given mutual-auth mode, using the
/// default (non-static-root) transport so it presents **no** verified client
/// consensus certificate. Used for S4/S5: the session cannot present a verified
/// client consensus identity, so the receiver must fail closed on
/// `missing_origin`. Returns `(Some(ctx), connected)` on success, or
/// `(None, false)` if the transport cannot even establish an unauthenticated
/// session (recorded honestly as partial coverage — never substituted with an
/// in-process envelope).
async fn build_unauth_driver(
    _material_dir: &Path,
    mode: MutualAuthMode,
    listen_addr: &str,
    receiver_addr: &str,
) -> (Option<P2pNodeContext>, bool) {
    let config = make_config(listen_addr, receiver_addr);
    // No pqc_root_config → default transport, no client consensus certificate.
    let built = P2pNodeBuilder::new()
        .with_num_validators(NUM_VALIDATORS)
        .with_mutual_auth_mode(mode)
        .build(&config, DRIVER_VID)
        .await;
    match built {
        Ok(ctx) => {
            let connected = wait_any_peer(&ctx).await;
            (Some(ctx), connected)
        }
        Err(e) => {
            eprintln!(
                "[run419-driver] unauthenticated {:?} driver could not build: {} \
                 (recorded as partial coverage; no in-process substitution)",
                mode, e
            );
            (None, false)
        }
    }
}

async fn wait_connected(ctx: &P2pNodeContext, target: &NodeId) -> (bool, bool) {
    let deadline = Instant::now() + Duration::from_secs(20);
    let mut saw_target = false;
    while Instant::now() < deadline {
        let peers = ctx.p2p_service.connected_peers();
        if peers.contains(target) {
            saw_target = true;
            break;
        }
        if ctx.p2p_service.connected_peer_count() > 0 {
            break;
        }
        tokio::time::sleep(Duration::from_millis(100)).await;
    }
    (ctx.p2p_service.connected_peer_count() > 0, saw_target)
}

async fn wait_any_peer(ctx: &P2pNodeContext) -> bool {
    let deadline = Instant::now() + Duration::from_secs(20);
    while Instant::now() < deadline {
        if ctx.p2p_service.connected_peer_count() > 0 {
            return true;
        }
        tokio::time::sleep(Duration::from_millis(100)).await;
    }
    ctx.p2p_service.connected_peer_count() > 0
}

/// Send `frames` to the receiver, pacing slightly so the deployed read/demux/
/// binary-consensus loop processes each before shutdown.
async fn send_frames(ctx: &P2pNodeContext, frames: &[P2pMessage]) {
    for frame in frames {
        ctx.p2p_service.broadcast(frame.clone());
        tokio::time::sleep(Duration::from_millis(150)).await;
    }
    // Drain time for the receiver's loop.
    tokio::time::sleep(Duration::from_millis(800)).await;
}

struct DriveOutcome {
    connected: bool,
    saw_receiver: bool,
    frames_sent: usize,
    local_node_id_prefix: String,
    receiver_node_id_prefix: String,
    note: String,
}

async fn drive(
    scenario: &str,
    material_dir: &Path,
    receiver_addr: &str,
    listen_addr: &str,
) -> DriveOutcome {
    match scenario {
        "s1-honest" => {
            let (ctx, connected, saw, rid) =
                build_authenticated_driver(material_dir, "v1", listen_addr, receiver_addr).await;
            let local = ctx.p2p_service.local_node_id();
            let frames = if connected {
                let f = vec![proposal_frame(DRIVER_VID)];
                send_frames(&ctx, &f).await;
                f.len()
            } else {
                0
            };
            let _ = P2pNodeBuilder::shutdown(ctx).await;
            DriveOutcome {
                connected,
                saw_receiver: saw,
                frames_sent: frames,
                local_node_id_prefix: node_id_prefix(&local),
                receiver_node_id_prefix: node_id_prefix(&rid),
                note: "authenticated validator 1 honest Proposal(proposer=1)".into(),
            }
        }
        "s2-impersonation" => {
            let (ctx, connected, saw, rid) =
                build_authenticated_driver(material_dir, "v1", listen_addr, receiver_addr).await;
            let local = ctx.p2p_service.local_node_id();
            let frames = if connected {
                // All five claimed-sender F6 branches, each claiming victim 0
                // while authenticated as validator 1.
                let f = vec![
                    proposal_frame(VICTIM_VID),
                    vote_frame(VICTIM_VID),
                    timeout_frame(VICTIM_VID),
                    restore_request_frame(VICTIM_VID),
                    restore_response_frame(VICTIM_VID),
                ];
                send_frames(&ctx, &f).await;
                f.len()
            } else {
                0
            };
            let _ = P2pNodeBuilder::shutdown(ctx).await;
            DriveOutcome {
                connected,
                saw_receiver: saw,
                frames_sent: frames,
                local_node_id_prefix: node_id_prefix(&local),
                receiver_node_id_prefix: node_id_prefix(&rid),
                note: "authenticated validator 1 claiming validator 0 across Proposal/Vote/Timeout/RestoreReq/RestoreResp".into(),
            }
        }
        "s3-newview" => {
            let (ctx, connected, saw, rid) =
                build_authenticated_driver(material_dir, "v1", listen_addr, receiver_addr).await;
            let local = ctx.p2p_service.local_node_id();
            let frames = if connected {
                let f = vec![newview_frame()];
                send_frames(&ctx, &f).await;
                f.len()
            } else {
                0
            };
            let _ = P2pNodeBuilder::shutdown(ctx).await;
            DriveOutcome {
                connected,
                saw_receiver: saw,
                frames_sent: frames,
                local_node_id_prefix: node_id_prefix(&local),
                receiver_node_id_prefix: node_id_prefix(&rid),
                note: "authenticated validator 1 NewView origin admission".into(),
            }
        }
        "s6-alt-leaf" => {
            // Alternate root-valid leaf for validator 1 (unconfigured NodeId).
            let (ctx, connected, saw, rid) =
                build_authenticated_driver(material_dir, "v1_alt", listen_addr, receiver_addr)
                    .await;
            let local = ctx.p2p_service.local_node_id();
            let frames = if connected {
                let f = vec![proposal_frame(DRIVER_VID)];
                send_frames(&ctx, &f).await;
                f.len()
            } else {
                0
            };
            let _ = P2pNodeBuilder::shutdown(ctx).await;
            DriveOutcome {
                connected,
                saw_receiver: saw,
                frames_sent: frames,
                local_node_id_prefix: node_id_prefix(&local),
                receiver_node_id_prefix: node_id_prefix(&rid),
                note: "root-valid but unconfigured alternate validator-1 leaf Proposal(proposer=1)"
                    .into(),
            }
        }
        "s4-optional-unauth" | "s5-disabled-unauth" => {
            let mode = if scenario == "s4-optional-unauth" {
                MutualAuthMode::Optional
            } else {
                MutualAuthMode::Disabled
            };
            let (maybe_ctx, connected) =
                build_unauth_driver(material_dir, mode, listen_addr, receiver_addr).await;
            let (local_prefix, frames) = match maybe_ctx {
                Some(ctx) => {
                    let local = ctx.p2p_service.local_node_id();
                    let sent = if connected {
                        let f = vec![proposal_frame(VICTIM_VID), newview_frame()];
                        send_frames(&ctx, &f).await;
                        f.len()
                    } else {
                        0
                    };
                    let _ = P2pNodeBuilder::shutdown(ctx).await;
                    (node_id_prefix(&local), sent)
                }
                None => (String::from("n/a"), 0),
            };
            DriveOutcome {
                connected,
                saw_receiver: false,
                frames_sent: frames,
                local_node_id_prefix: local_prefix,
                receiver_node_id_prefix: String::from("n/a"),
                note: format!(
                    "unauthenticated ingress under {:?}: Proposal + NewView",
                    mode
                ),
            }
        }
        other => die(&format!("unknown scenario '{}'", other)),
    }
}

fn usage() -> ! {
    eprintln!(
        "usage:\n  run_419_f6_release_binary_binding_driver gen-material <DIR>\n  \
         run_419_f6_release_binary_binding_driver drive <SCENARIO> <MATERIAL_DIR> \
         <RECEIVER_LOOPBACK_ADDR> <DRIVER_LISTEN_LOOPBACK_ADDR> <OUT_FILE>\n\n\
         SCENARIO ∈ s1-honest | s2-impersonation | s3-newview | s6-alt-leaf | \
         s4-optional-unauth | s5-disabled-unauth"
    );
    exit(2);
}

fn main() {
    let args: Vec<String> = env::args().collect();
    if args.len() < 2 {
        usage();
    }
    match args[1].as_str() {
        "gen-material" => {
            if args.len() != 3 {
                usage();
            }
            gen_material(&PathBuf::from(&args[2]));
        }
        "drive" => {
            if args.len() != 7 {
                usage();
            }
            let scenario = args[2].clone();
            let material_dir = PathBuf::from(&args[3]);
            let receiver_addr = args[4].clone();
            let listen_addr = args[5].clone();
            let out_file = PathBuf::from(&args[6]);
            require_loopback(&receiver_addr);
            require_loopback(&listen_addr);
            if !material_dir.is_dir() {
                die(&format!(
                    "material dir '{}' not found",
                    material_dir.display()
                ));
            }
            let rt = tokio::runtime::Builder::new_multi_thread()
                .enable_all()
                .build()
                .expect("tokio runtime");
            let outcome = rt.block_on(drive(
                &scenario,
                &material_dir,
                &receiver_addr,
                &listen_addr,
            ));
            let body = format!(
                "scenario: {}\nconnected: {}\nsaw_receiver_node_id: {}\nframes_sent: {}\n\
                 driver_node_id_prefix: {}\nreceiver_node_id_prefix: {}\nnote: {}\n",
                scenario,
                outcome.connected,
                outcome.saw_receiver,
                outcome.frames_sent,
                outcome.local_node_id_prefix,
                outcome.receiver_node_id_prefix,
                outcome.note,
            );
            write_file(&out_file, &body);
            print!("{}", body);
            // A scenario that never connected (except the intentionally
            // fail-closed unauth modes, which the harness evaluates from the
            // receiver's /metrics) is a driver-side failure.
            if !outcome.connected && !scenario.contains("unauth") {
                die(&format!(
                    "scenario '{}' did not establish a session",
                    scenario
                ));
            }
        }
        _ => usage(),
    }
}
