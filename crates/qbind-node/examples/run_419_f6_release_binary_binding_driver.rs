//! Run 419 — F6 standalone release-binary KEMTLS peer → consensus sender
//! binding **evidence driver** (Cargo example; NOT part of the `qbind-node`
//! production CLI).
//!
//! # Purpose
//!
//! Run 418 remediated finding **F6** (authenticated KEMTLS peer → consensus
//! sender binding) in production code and proved it with unit + in-process
//! demux-chain tests only. This helper produces the missing **standalone
//! release-binary** evidence: it drives a real, loopback, cross-process KEMTLS
//! session against the deployed `target/release/qbind-node` receiver and lets
//! the Run 419 harness observe the deployed node's live
//! `qbind_consensus_binding_total{result="…"}` `/metrics` family reacting to a
//! fixed, enumerated set of consensus frames.
//!
//! It changes **no** production behavior. It uses only pre-existing public
//! production APIs (`P2pNodeBuilder`, the `pqc_root_config` loaders, the real
//! `P2pMessage`/`ConsensusNetMsg` wire types, and the real `qbind-wire`
//! consensus encoders) and the same static-root KEMTLS framing path the
//! deployed binary uses.
//!
//! # Safety envelope (enforced, not documented-only)
//!
//! * DevNet-only: every driver node is built with `NetworkEnvironment::Devnet`.
//!   MainNet/TestNet are impossible to select — there is no environment
//!   argument.
//! * Loopback-only: the receiver target and the driver's own listener must be
//!   `127.0.0.1`/`::1`; any other address exits non-zero before any socket is
//!   opened.
//! * Fixed enumerated scenarios only. There is **no** arbitrary-payload-hex,
//!   arbitrary-sender-selection, or general-purpose forged-message mode. The
//!   claimed-sender values are hardcoded per scenario (driver = validator 1,
//!   impersonated victim = validator 0, receiver = validator 2).
//! * Bounded message count: each scenario sends at most a handful of frames.
//! * No secret logging: the helper never prints KEM secret keys, raw cert
//!   bytes, root public-key blobs, or absolute private paths. Only truncated
//!   NodeId prefixes and loopback endpoints are printed.
//! * Malformed arguments, a non-loopback target, or a scenario/connect failure
//!   exit non-zero.
//!
//! Temporary PQC material (root signing key held **in memory only**; leaf KEM
//! secret files created mode `0600`) is generated by the `gen-material`
//! subcommand into a caller-provided temp directory and removed by the harness.
//!
//! # Subcommands
//!
//! ```text
//! run_419_f6_release_binary_binding_driver gen-material <DIR>
//! run_419_f6_release_binary_binding_driver drive <SCENARIO> <MATERIAL_DIR> \
//!     <RECEIVER_LOOPBACK_ADDR> <DRIVER_LISTEN_LOOPBACK_ADDR> <OUT_FILE>
//! ```
//!
//! `SCENARIO` is one of:
//! `s1-honest`, `s2-impersonation`, `s3-newview`, `s6-alt-leaf`,
//! `s4-optional-unauth`, `s5-disabled-unauth`.

