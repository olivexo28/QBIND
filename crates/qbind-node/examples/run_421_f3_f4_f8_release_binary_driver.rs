//! Run 421 — F3/F4/F8 unavailable-authority fail-closed **release-binary
//! evidence driver** (Cargo example; NOT part of the `qbind-node` production
//! CLI).
//!
//! # Purpose
//!
//! Run 420 corrected the former Proposal/Vote `verification_ctx == None`
//! fail-open bypass in the binary-path consensus loop with an explicit typed
//! [`ConsensusVerificationPolicy`] (`Required` default, test-only
//! `LocalFixtureUnsigned`). Run 420 proved the correction with production-path
//! loop tests only; it did NOT capture standalone release-binary runtime
//! evidence (`RELEASE_BINARY_EVIDENCE=NOT-CAPTURED`).
//!
//! This helper produces that missing evidence. It drives real, loopback,
//! cross-process KEMTLS sessions against the deployed
//! `target/release/qbind-node` receiver (which has NO configured consensus
//! verification authority, so `verification_ctx == None` and the production
//! default `Required` policy is active) and lets the Run 421 harness observe
//! the deployed node's live `/metrics` reacting to a fixed, enumerated set of
//! consensus frames.
//!
//! It proves the **unavailable-authority fail-closed boundary** only: an
//! authenticated, F6-authorized Proposal/Vote is rejected because consensus
//! verification authority is unavailable. It does NOT — and cannot — prove
//! configured-authority cryptographic signature success, because no consensus
//! signing authority exists on the standalone binary.
//!
//! It changes **no** production behavior. It reuses the Run 419 driver's
//! material-generation and static-root/KEMTLS session patterns and only the
//! pre-existing public production APIs (`P2pNodeBuilder`, the `pqc_root_config`
//! loaders, the real `P2pMessage`/`ConsensusNetMsg` wire types, and the real
//! `qbind-wire` consensus encoders).
//!
//! # Safety envelope (enforced, not documented-only)
//!
//! * DevNet-only: every driver node is built with `NetworkEnvironment::Devnet`.
//!   MainNet/TestNet are impossible to select — there is no environment
//!   argument.
//! * Loopback-only: the receiver target and the driver's own listener must be
//!   `127.0.0.1`/`::1`; any other address exits non-zero before any socket is
//!   opened.
//! * Fixed enumerated scenarios only. There is **no** arbitrary-payload-hex,
//!   arbitrary-sender-selection, arbitrary-suite, arbitrary-signature, or
//!   general-purpose forged-message mode. The claimed-sender, signature shape,
//!   and suite id are hardcoded per scenario (driver = validator 1,
//!   impersonated victim = validator 0, receiver = validator 2).
//! * Bounded message count: each scenario sends at most a handful of frames.
//! * No secret logging: the helper never prints KEM secret keys, raw cert
//!   bytes, root public-key blobs, complete signatures, or absolute private
//!   paths. Only truncated NodeId prefixes and loopback endpoints are printed.
//! * Malformed arguments, a non-loopback target, or a scenario/connect failure
//!   exit non-zero.
//!
//! Temporary PQC material (root signing key held **in memory only**; leaf KEM
//! secret files created mode `0600`) is generated by the `gen-material`
//! subcommand into a caller-provided temp directory and removed by the harness.
//!
//! # Subcommands
//!
//! ```text
//! run_421_f3_f4_f8_release_binary_driver gen-material <DIR>
//! run_421_f3_f4_f8_release_binary_driver drive <SCENARIO> <MATERIAL_DIR> \
//!     <RECEIVER_LOOPBACK_ADDR> <DRIVER_LISTEN_LOOPBACK_ADDR> <OUT_FILE>
//! ```
//!
//! `SCENARIO` is one of:
//! `s2-proposal`, `s3-vote`, `s4-mismatch`, `s5-badsig`, `s6-badsuite`.

