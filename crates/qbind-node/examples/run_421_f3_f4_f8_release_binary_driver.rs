// Fixed enumerated identities (no arbitrary sender selection).
const DRIVER_VID: u64 = 1;
const VICTIM_VID: u64 = 0;
const RECEIVER_VID: u64 = 2;
const NUM_VALIDATORS: usize = 3;

// Fixed, non-arbitrary signature/suite shapes used by the enumerated scenarios.
// `MISSING` = empty (honest / missing signature). `MALFORMED` = a short fixed
// non-empty pattern that is NOT a valid consensus signature. `WRONG_SUITE` is a
// fixed unsupported suite id. None of these are caller-controllable.
const SIG_MISSING: &[u8] = &[];
const SIG_MALFORMED: &[u8] = &[0xABu8; 8];
const WRONG_SUITE_ID: u16 = 0x00EE;

fn die(msg: &str) -> ! {
    eprintln!("[run421-driver] FATAL: {}", msg);
    exit(2);
}

fn hex_lower(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        use std::fmt::Write as _;
        let _ = write!(s, "{:02x}", b);
    }
    s
}

/// Truncated (first 8 bytes) NodeId prefix — publish-safe.
fn node_id_prefix(node_id: &NodeId) -> String {
    hex_lower(&node_id.as_bytes()[..8])
}

fn write_file(path: &Path, contents: &str) {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).expect("create parent dir");
    }
    let mut f = fs::File::create(path).expect("create file");
    f.write_all(contents.as_bytes()).expect("write file");
}

/// Write a KEM secret key file with owner-only `0600` permissions.
fn write_secret_file(path: &Path, bytes: &[u8]) {
    fs::write(path, bytes).expect("write secret file");
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perm = fs::metadata(path).expect("stat secret file").permissions();
        perm.set_mode(0o600);
        fs::set_permissions(path, perm).expect("chmod 0600 secret file");
    }
}

/// The `qbind-val-<vid>` validator-identity bytes (mirrors the production
/// DevNet root helper's `vid_bytes`).
fn validator_id_bytes_for(vid: u64) -> [u8; 32] {
    let mut out = [0u8; 32];
    let s = format!("qbind-val-{}", vid);
    let n = s.len().min(32);
    out[..n].copy_from_slice(&s.as_bytes()[..n]);
    out
}

/// Assert the address is loopback (`127.0.0.1` / `::1`); exit non-zero
/// otherwise. Called before any socket is bound or dialed.
fn require_loopback(addr: &str) {
    let host = match addr.rsplit_once(':') {
        Some((h, _)) => h.trim_start_matches('[').trim_end_matches(']'),
        None => die(&format!("address '{}' is not host:port", addr)),
    };
    match host.parse::<IpAddr>() {
        Ok(ip) if ip.is_loopback() => {}
        _ => die(&format!(
            "refusing non-loopback address '{}': Run 421 is loopback-only",
            addr
        )),
    }
}

// ---------------------------------------------------------------------------
// Material generation (root in-memory only; leaf KEM secrets mode 0600).
// ---------------------------------------------------------------------------

/// Mint a fresh ML-DSA-44 root and per-validator ML-KEM-768 leaves for
/// validators 0/1/2. All certs are signed by the SAME in-memory root; the root
/// signing key is discarded when this process exits and never written to disk.
fn gen_material(dir: &Path) {
    fs::create_dir_all(dir).expect("mkdir material dir");
    let root = mint_devnet_root().expect("mint devnet root");
    let root_id_hex = hex_lower(&root.root_key_id);
    let trusted_spec = format!(
        "{}:{}:{}",
        root_id_hex,
        PQC_TRANSPORT_SUITE_ML_DSA_44,
        hex_lower(&root.root_pk)
    );
    write_file(&dir.join("trusted-root.spec"), &trusted_spec);
    write_file(&dir.join("root.id.hex"), &root_id_hex);

    let mint_leaf = |validator_id: [u8; 32], cert_name: &str, sk_name: &str| {
        let (kem_pk, kem_sk) = MlKem768Backend::generate_keypair().expect("ml-kem keygen");
        let spec = LeafCertSpec {
            validator_id,
            root_key_id: root.root_key_id,
            leaf_kem_suite_id: KEM_SUITE_ML_KEM_768,
            leaf_kem_pk: kem_pk,
            not_before: 0,
            not_after: u64::MAX,
            ext_bytes: vec![],
        };
        let cert = issue_leaf_delegation_cert(&spec, &root.root_sk).expect("issue leaf cert");
        fs::write(dir.join(cert_name), encode_cert(&cert)).expect("write cert");
        write_secret_file(&dir.join(sk_name), &kem_sk);
    };

    for vid in 0..NUM_VALIDATORS as u64 {
        mint_leaf(
            validator_id_bytes_for(vid),
            &format!("v{}.cert.bin", vid),
            &format!("v{}.kem.sk.bin", vid),
        );
    }

    println!(
        "gen_material_ok: root_id={} validators={}",
        root_id_hex, NUM_VALIDATORS
    );
}

// ---------------------------------------------------------------------------
// Static-root config loading (public production loaders).
// ---------------------------------------------------------------------------

fn load_trusted_roots(dir: &Path) -> Vec<PqcTrustedRoot> {
    let spec = fs::read_to_string(dir.join("trusted-root.spec")).expect("read trusted-root.spec");
    parse_pqc_trusted_root_specs(&[spec.trim().to_string()], true).expect("parse trusted root spec")
}

fn peer_leaf_cert(dir: &Path, vid: u64) -> PqcPeerLeafCert {
    let spec = format!(
        "{}:{}",
        vid,
        dir.join(format!("v{}.cert.bin", vid)).display()
    );
    parse_pqc_peer_leaf_cert_spec(&spec).expect("parse peer leaf cert spec")
}

/// Load the driver's static-root config for its authenticated validator-1
/// identity, dialing the receiver (validator 2).
fn driver_static_root_config(dir: &Path) -> PqcStaticRootConfig {
    let leaf = PqcLeafCredentialPaths {
        cert_path: dir.join("v1.cert.bin"),
        kem_sk_path: dir.join("v1.kem.sk.bin"),
    }
    .load()
    .expect("load driver leaf credentials");
    PqcStaticRootConfig {
        mode: PqcRootMode::PqcStaticRoot,
        trusted_roots: load_trusted_roots(dir),
        leaf_credentials: Some(leaf),
        peer_leaf_certs: vec![peer_leaf_cert(dir, RECEIVER_VID)],
    }
}

fn cert_derived_node_id_from_file(cert_path: &Path) -> NodeId {
    use qbind_wire::io::WireDecode;
    let bytes = fs::read(cert_path).expect("read cert file");
    let mut slice: &[u8] = &bytes;
    let cert = NetworkDelegationCert::decode(&mut slice).expect("decode cert");
    NodeId::new(derive_node_id_from_pubkey(&cert.leaf_kem_pk))
}

// ---------------------------------------------------------------------------
// Consensus frame builders (real wire encoders; controlled claimed sender,
// fixed per-scenario signature/suite shapes).
// ---------------------------------------------------------------------------

fn encode_wire<T: WireEncode>(t: &T) -> Vec<u8> {
    let mut out = Vec::new();
    t.encode(&mut out);
    out
}

fn proposal_frame(proposer: u64, suite_id: u16, signature: &[u8]) -> P2pMessage {
    let proposal = BlockProposal {
        header: BlockHeader {
            version: 1,
            chain_id: 1,
            epoch: 0,
            height: 0,
            round: 0,
            parent_block_id: [0xFF; 32],
            payload_hash: [0u8; 32],
            proposer_index: proposer as u16,
            suite_id,
            tx_count: 0,
            timestamp: 0,
            payload_kind: qbind_wire::PAYLOAD_KIND_NORMAL,
            next_epoch: 0,
            batch_commitment: [0u8; 32],
        },
        qc: None,
        txs: vec![],
        signature: signature.to_vec(),
    };
    P2pMessage::Consensus(ConsensusNetMsg::Proposal(encode_wire(&proposal)))
}

fn vote_frame(voter: u64, suite_id: u16, signature: &[u8]) -> P2pMessage {
    let vote = Vote {
        version: 1,
        chain_id: 1,
        epoch: 0,
        height: 0,
        round: 0,
        step: 0,
        block_id: [0u8; 32],
        validator_index: voter as u16,
        suite_id,
        signature: signature.to_vec(),
    };
    P2pMessage::Consensus(ConsensusNetMsg::Vote(encode_wire(&vote)))
}

