/// Build an authenticated (static-root Required) validator-1 driver node and
/// wait until the receiver's cert-derived NodeId is registered as a connected
/// peer.
async fn build_authenticated_driver(
    material_dir: &Path,
    listen_addr: &str,
    receiver_addr: &str,
) -> (P2pNodeContext, bool, bool, NodeId) {
    let config = make_config(listen_addr, receiver_addr);
    let pqc = driver_static_root_config(material_dir);
    let ctx = P2pNodeBuilder::new()
        .with_num_validators(NUM_VALIDATORS)
        .with_mutual_auth_mode(MutualAuthMode::Required)
        .with_pqc_root_config(pqc)
        .build(&config, DRIVER_VID)
        .await
        .expect("build authenticated driver node");
    let receiver_node_id = cert_derived_node_id_from_file(&material_dir.join("v2.cert.bin"));
    let (connected, saw_receiver) = wait_connected(&ctx, &receiver_node_id).await;
    (ctx, connected, saw_receiver, receiver_node_id)
}

async fn wait_connected(ctx: &P2pNodeContext, target: &NodeId) -> (bool, bool) {
    let deadline = Instant::now() + Duration::from_secs(20);
    let mut saw_target = false;
    while Instant::now() < deadline {
        let peers = ctx.p2p_service.connected_peers();
        if peers.contains(target) {
            saw_target = true;
            break;
        }
        if ctx.p2p_service.connected_peer_count() > 0 {
            break;
        }
        tokio::time::sleep(Duration::from_millis(100)).await;
    }
    (ctx.p2p_service.connected_peer_count() > 0, saw_target)
}

/// Send `frames` to the receiver, pacing slightly so the deployed read/demux/
/// binary-consensus loop processes each before shutdown.
async fn send_frames(ctx: &P2pNodeContext, frames: &[P2pMessage]) {
    for frame in frames {
        ctx.p2p_service.broadcast(frame.clone());
        tokio::time::sleep(Duration::from_millis(150)).await;
    }
    tokio::time::sleep(Duration::from_millis(2000)).await;
}

struct DriveOutcome {
    connected: bool,
    saw_receiver: bool,
    frames_sent: usize,
    local_node_id_prefix: String,
    receiver_node_id_prefix: String,
    note: String,
}

/// The fixed frame list for each enumerated scenario. No caller input other
/// than the scenario name selects these.
fn scenario_frames(scenario: &str) -> Result<(Vec<P2pMessage>, &'static str), String> {
    let default_suite = qbind_wire::DEFAULT_CONSENSUS_SUITE_ID;
    match scenario {
        // Honest authenticated validator-1 Proposal with a missing signature.
        // F6 accepts; the Required unavailable-context gate rejects fail-closed.
        "s2-proposal" => Ok((
            vec![proposal_frame(DRIVER_VID, default_suite, SIG_MISSING)],
            "authenticated validator 1 honest Proposal(proposer=1) — expect inbound proposal context-unavailable rejection",
        )),
        // Honest authenticated validator-1 Vote with a missing signature.
        "s3-vote" => Ok((
            vec![vote_frame(DRIVER_VID, default_suite, SIG_MISSING)],
            "authenticated validator 1 honest Vote(voter=1) — expect inbound vote context-unavailable rejection",
        )),
        // F6 mismatch: authenticated as validator 1 but claiming validator 0.
        // F6 must reject BEFORE the Run 420 context gate for both message types.
        "s4-mismatch" => Ok((
            vec![
                proposal_frame(VICTIM_VID, default_suite, SIG_MISSING),
                vote_frame(VICTIM_VID, default_suite, SIG_MISSING),
            ],
            "authenticated validator 1 claiming validator 0 (Proposal+Vote) — expect claimed_sender_mismatch x2, context counters unchanged",
        )),
        // Malformed (non-empty, invalid) signatures. Under Required+None the
        // context gate still rejects before any signature parsing.
        "s5-badsig" => Ok((
            vec![
                proposal_frame(DRIVER_VID, default_suite, SIG_MALFORMED),
                vote_frame(DRIVER_VID, default_suite, SIG_MALFORMED),
            ],
            "authenticated validator 1 malformed-signature Proposal+Vote — expect context-unavailable rejection (no signature parsing)",
        )),
        // Wrong/unsupported suite id. Under Required+None the context gate still
        // rejects before any suite enforcement.
        "s6-badsuite" => Ok((
            vec![
                proposal_frame(DRIVER_VID, WRONG_SUITE_ID, SIG_MISSING),
                vote_frame(DRIVER_VID, WRONG_SUITE_ID, SIG_MISSING),
            ],
            "authenticated validator 1 wrong-suite Proposal+Vote — expect context-unavailable rejection (no suite enforcement)",
        )),
        other => Err(format!("unknown scenario '{}'", other)),
    }
}

async fn drive(
    scenario: &str,
    material_dir: &Path,
    receiver_addr: &str,
    listen_addr: &str,
) -> DriveOutcome {
    let (frames, note) = match scenario_frames(scenario) {
        Ok(v) => v,
        Err(e) => die(&e),
    };
    let (ctx, connected, saw, rid) =
        build_authenticated_driver(material_dir, listen_addr, receiver_addr).await;
    let local = ctx.p2p_service.local_node_id();
    let sent = if connected {
        send_frames(&ctx, &frames).await;
        frames.len()
    } else {
        0
    };
    let _ = P2pNodeBuilder::shutdown(ctx).await;
    DriveOutcome {
        connected,
        saw_receiver: saw,
        frames_sent: sent,
        local_node_id_prefix: node_id_prefix(&local),
        receiver_node_id_prefix: node_id_prefix(&rid),
        note: note.to_string(),
    }
}

fn usage() -> ! {
    eprintln!(
        "usage:\n  run_421_f3_f4_f8_release_binary_driver gen-material <DIR>\n  \
         run_421_f3_f4_f8_release_binary_driver drive <SCENARIO> <MATERIAL_DIR> \
         <RECEIVER_LOOPBACK_ADDR> <DRIVER_LISTEN_LOOPBACK_ADDR> <OUT_FILE>\n\n\
         SCENARIO ∈ s2-proposal | s3-vote | s4-mismatch | s5-badsig | s6-badsuite"
    );
    exit(2);
}

fn main() {
    let args: Vec<String> = env::args().collect();
    if args.len() < 2 {
        usage();
    }
    match args[1].as_str() {
        "gen-material" => {
            if args.len() != 3 {
                usage();
            }
            gen_material(&PathBuf::from(&args[2]));
        }
        "drive" => {
            if args.len() != 7 {
                usage();
            }
            let scenario = args[2].clone();
            let material_dir = PathBuf::from(&args[3]);
            let receiver_addr = args[4].clone();
            let listen_addr = args[5].clone();
            let out_file = PathBuf::from(&args[6]);
            require_loopback(&receiver_addr);
            require_loopback(&listen_addr);
            if !material_dir.is_dir() {
                die(&format!(
                    "material dir '{}' not found",
                    material_dir.display()
                ));
            }
            let rt = tokio::runtime::Builder::new_multi_thread()
                .enable_all()
                .build()
                .expect("tokio runtime");
            let outcome = rt.block_on(drive(
                &scenario,
                &material_dir,
                &receiver_addr,
                &listen_addr,
            ));
            let body = format!(
                "scenario: {}\nconnected: {}\nsaw_receiver_node_id: {}\nframes_sent: {}\n\
                 driver_node_id_prefix: {}\nreceiver_node_id_prefix: {}\nnote: {}\n",
                scenario,
                outcome.connected,
                outcome.saw_receiver,
                outcome.frames_sent,
                outcome.local_node_id_prefix,
                outcome.receiver_node_id_prefix,
                outcome.note,
            );
            write_file(&out_file, &body);
            print!("{}", body);
            if !outcome.connected {
                die(&format!(
                    "scenario '{}' did not establish a session",
                    scenario
                ));
            }
        }
        _ => usage(),
    }
}
